// Dynamic runtime directory that stores teachers discovered live from routine API
const dynamicFacultyRegistry = new Map<string, FacultyMeta>();

/**
 * Register or update teacher metadata found during live scraping
 */
export function registerDynamicFaculty(meta: FacultyMeta): FacultyMeta {
  const code = meta.code.trim().toUpperCase();
  const existing = getFacultyByCode(code);
  
  const merged: FacultyMeta = {
    code,
    name: meta.name && !meta.name.startsWith('Faculty (') ? meta.name : (existing?.name || meta.name || code),
    department: meta.department || existing?.department || 'CSE',
    designation: meta.designation || existing?.designation,
    room: meta.room || existing?.room,
    email: meta.email || existing?.email,
    phone: (meta.phone && meta.phone !== '0' && meta.phone.trim().length > 4) ? meta.phone : (existing?.phone || undefined),
    employeeId: meta.employeeId || existing?.employeeId,
    image: meta.image || existing?.image || imagesMap[code],
    aliases: Array.from(new Set([...(existing?.aliases || []), ...(meta.aliases || [])])),
  };

  dynamicFacultyRegistry.set(code, merged);
  return merged;
}

/**
 * Normalizes query string for fuzzy and partial matching
 */
function normalizeQuery(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Look up faculty by code or alias
 */
export function getFacultyByCode(code: string): FacultyMeta | undefined {
  const clean = code.trim().toUpperCase();
  if (!clean) return undefined;

  // 1. Check dynamic runtime registry
  if (dynamicFacultyRegistry.has(clean)) {
    return dynamicFacultyRegistry.get(clean);
  }

  // 2. Exact match in static directory
  const direct = DIU_FACULTY_DIRECTORY.find((f) => f.code === clean);
  if (direct) {
    const withImg: FacultyMeta = {
      ...direct,
      image: direct.image || imagesMap[direct.code],
    };
    return withImg;
  }

  // 3. Alias match in static directory
  const byAlias = DIU_FACULTY_DIRECTORY.find(
    (f) => f.aliases && f.aliases.some((a) => a.toUpperCase() === clean)
  );
  if (byAlias) {
    return {
      ...byAlias,
      image: byAlias.image || imagesMap[byAlias.code],
    };
  }

  return undefined;
}

export function getAllFaculty(): FacultyMeta[] {
  return DIU_FACULTY_DIRECTORY;
}

function levenshteinDistance(a: string, b: string): number {
  if (a === b) return 0;
  if (!a) return b.length;
  if (!b) return a.length;
  const dp: number[] = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let prev = dp[0];
    dp[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const temp = dp[j];
      if (a[i - 1] === b[j - 1]) {
        dp[j] = prev;
      } else {
        dp[j] = Math.min(prev, dp[j - 1], dp[j]) + 1;
      }
      prev = temp;
    }
  }
  return dp[b.length];
}

const HONORIFICS = new Set([
  'md',
  'dr',
  'prof',
  'mr',
  'ms',
  'mrs',
  'engr',
  'mohammed',
  'muhammad',
  'sir',
  'professor',
  'lecturer',
]);

export function searchAndRankFaculty(
  query: string,
  limit = 15
): Array<{ faculty: FacultyMeta; score: number }> {
  const q = query.trim();
  if (!q) {
    return DIU_FACULTY_DIRECTORY.slice(0, limit).map((f) => ({
      faculty: { ...f, image: f.image || imagesMap[f.code] },
      score: 1,
    }));
  }

  const cleanQ = normalizeQuery(q);
  const upperQ = q.toUpperCase();
  const lowerQ = cleanQ;

  // Combine dynamic and static
  const allKnown = new Map<string, FacultyMeta>();
  for (const f of DIU_FACULTY_DIRECTORY) {
    allKnown.set(f.code, { ...f, image: f.image || imagesMap[f.code] });
  }
  for (const [code, f] of dynamicFacultyRegistry.entries()) {
    allKnown.set(code, f);
  }

  const results: Array<{ faculty: FacultyMeta; score: number }> = [];

  for (const f of allKnown.values()) {
    let score = 0;
    const fCode = f.code.toUpperCase();
    const lowerCode = f.code.toLowerCase();
    const fName = f.name;
    const cleanName = normalizeQuery(fName);
    const nameWords = fName.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
    const coreWords = nameWords.filter((w) => !HONORIFICS.has(w));

    // 1. Exact Teacher Code match (Highest Priority)
    if (fCode === upperQ || lowerCode === lowerQ) {
      score = Math.max(score, 1000);
    }

    // 2. Teacher Code prefix / substring for normal typing
    if (lowerQ.length >= 2 && lowerCode.startsWith(lowerQ)) {
      score = Math.max(score, 450);
    }

    // 3. User typed initial with garbage/prefix typos or extra letters (e.g. "slrkr", "rkrr", "mrkr")
    if (lowerCode.length >= 3) {
      if (lowerQ.includes(lowerCode)) {
        // e.g. "slrkr" contains "rkr", "rkrr" contains "rkr"
        score = Math.max(score, 380);
      } else {
        const d = levenshteinDistance(lowerCode, lowerQ);
        if (d === 1) {
          score = Math.max(score, 320);
        } else if (d === 2 && lowerQ.length <= 6) {
          score = Math.max(score, 250);
        }
      }
    } else if (lowerCode.length === 2) {
      // 2-letter teacher code (e.g. "AM", "AS")
      // Only match embedded/fuzzy if the query is short (<= 3 chars) so it doesn't match long words
      if (lowerQ.length <= 3 && (lowerQ.startsWith(lowerCode) || lowerQ.endsWith(lowerCode))) {
        score = Math.max(score, 300);
      }
    }

    // 4. Aliases matching
    if (f.aliases && Array.isArray(f.aliases)) {
      for (const a of f.aliases) {
        const cleanA = normalizeQuery(a);
        if (cleanA === lowerQ || a.toUpperCase() === upperQ) {
          score = Math.max(score, 500);
        } else if (cleanA.startsWith(lowerQ)) {
          score = Math.max(score, 350);
        } else if (lowerQ.includes(cleanA) && cleanA.length >= 3) {
          score = Math.max(score, 300);
        }
      }
    }

    // 5. Direct Name Word Matches
    for (const w of coreWords) {
      if (w === lowerQ) {
        score = Math.max(score, 400);
      } else if (w.startsWith(lowerQ) && lowerQ.length >= 3) {
        score = Math.max(score, 280);
      } else if (w.includes(lowerQ) && lowerQ.length >= 4) {
        score = Math.max(score, 220);
      }
    }

    // 6. Full Clean Name match / prefix
    if (cleanName === lowerQ) {
      score = Math.max(score, 450);
    } else if (cleanName.startsWith(lowerQ) && lowerQ.length >= 3) {
      score = Math.max(score, 300);
    } else if (cleanName.includes(lowerQ) && lowerQ.length >= 4) {
      score = Math.max(score, 260);
    }

    // 7. Fuzzy Name Word Typos (e.g. "rashedul" -> "rasedul", "rofiq" -> "rafiq", "nadeem" -> "nadim")
    if (lowerQ.length >= 4) {
      for (const w of coreWords) {
        if (w.length < 3) continue;
        const d = levenshteinDistance(w, lowerQ);
        if (d === 1) {
          score = Math.max(score, 240);
        } else if (d === 2 && lowerQ.length >= 5) {
          score = Math.max(score, 180);
        }
      }
    }

    if (score > 0) {
      results.push({ faculty: f, score });
    }
  }

  results.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    return a.faculty.name.localeCompare(b.faculty.name);
  });

  return results.slice(0, limit);
}

/**
 * Search faculty directory by name, code, designation, or department
 */
export function searchFaculty(query: string, limit = 15): FacultyMeta[] {
  return searchAndRankFaculty(query, limit).map((r) => r.faculty);
}
